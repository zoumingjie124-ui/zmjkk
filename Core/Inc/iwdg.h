/**
  ******************************************************************************
  * @file    iwdg.h
  * @brief   独立看门狗：给"软件闸门"补一条硬件后路。
  *
  * 为什么加热类项目必须有它：
  *   Heater 的输出总闸（s_hw_en）是一个软件变量。一旦 CPU 挂了
  *   （HardFault、Error_Handler 死循环、某个 while 卡住），TIM1 仍然在
  *   独立运行，PA8 会保持最后一次的占空比 —— 加热器持续加热，
  *   而软件超温联锁永远不会再执行。
  *
  *   IWDG 由独立的 LSI 时钟驱动，CPU 停住就没人喂狗，超时后硬件复位。
  *   复位后 PA8 回到上电默认（浮空输入）+ 板上 10k 下拉 -> 加热器关断。
  *   所以 IWDG 不是"锦上添花"，而是这条失效链上唯一不依赖 CPU 的兜底。
  *
  * 时限选择：
  *   LSI 标称 40kHz（规格范围 30~60kHz），预分频 64 -> 625Hz，
  *   重装 625 -> 标称 1.0s（LSI 偏差下约 0.67~1.33s）。
  *   主循环里最长的一次阻塞是 Usart_Send 的 100ms（HAL 超时），
  *   加上 Flash 擦写 40ms、OLED 整屏刷新，最坏约 250ms，留有 2.5 倍余量。
  ******************************************************************************
  */
#ifndef __IWDG_H
#define __IWDG_H

#include <stdint.h>

/* 启动看门狗。必须在所有外设初始化完成、进入主循环之前调用：
   一旦启动就无法关闭，若放得太早，慢速初始化会被误复位。 */
void MX_IWDG_Init(void);

/* 喂狗。放在主循环每轮开头：只要循环在跑就一定喂到，
   卡在任何一处都会停止喂狗 -> 超时复位。 */
void IWDG_Feed(void);

/* 本次复位是否由看门狗触发（上电时读一次 RCC_CSR 并清标志，之后返回缓存值） */
uint8_t IWDG_ResetWasWatchdog(void);

#endif /* __IWDG_H */
